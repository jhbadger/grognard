def _build():
    out = {}
    for ch, (top, art) in GLYPHS.items():
        rows = art.split('/')
        w = max(len(r) for r in rows)
        bits = [''] * HEIGHT
        for i, r in enumerate(rows):
            if top + i < HEIGHT:
                bits[top + i] = r.ljust(w, '.')
        runs = []
        for y, r in enumerate(bits):
            x = 0
            while x < len(r):
                if r[x] == '#':
                    x0 = x
                    while x < len(r) and r[x] == '#':
                        x += 1
                    runs.append((x0, y, x - x0))
                else:
                    x += 1
        out[ch] = (w, runs)
    return out


FONT = _build()


def glyph(ch):
    g = FONT.get(ch)
    if g is None:
        # an accented letter: the plain one (u for \u00fc, e for \u00e9)
        import unicodedata
        base = unicodedata.normalize('NFKD', ch)[:1]
        g = FONT.get(base) or FONT['?']
        FONT[ch] = g
    return g


def width(s, scale=1):
    """The width of s in pixels."""
    if not s:
        return 0
    return (sum(glyph(c)[0] + 1 for c in s) - 1) * scale


def wrap(text, maxw, scale=1):
    """Break text into lines no wider than maxw pixels; '\\n' forces a
    break."""
    lines = []
    for para in text.split('\n'):
        words = para.split(' ')
        line = ''
        for w in words:
            trial = w if not line else line + ' ' + w
            if width(trial, scale) <= maxw or not line:
                line = trial
            else:
                lines.append(line)
                line = w
        lines.append(line)
    return lines
